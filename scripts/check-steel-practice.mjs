import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdtemp,mkdir,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createTabletopServer} from '../server/index.mjs';
const require=createRequire(process.env.PLAYWRIGHT_MODULE_PATH||import.meta.url);
const {chromium}=require('playwright');
const dataDir=await mkdtemp(join(tmpdir(),'steel-practice-'));
const app=await createTabletopServer({dataDir});
await new Promise(resolve=>app.server.listen(0,'127.0.0.1',resolve));
const base=`http://127.0.0.1:${app.server.address().port}`;
let browser;
try{
 browser=await chromium.launch({channel:process.env.PLAYWRIGHT_CHANNEL||'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:960}}),errors=[];
 page.on('pageerror',error=>errors.push(error.message));page.setDefaultTimeout(10000);
 await page.goto(base+'/games/steel-arc/index.html');
 await page.locator('[data-action="practice"]').click();
 await page.waitForFunction(()=>!document.querySelector('#fire-button').disabled);
 assert.equal(await page.locator('#enemy-name').textContent(),'固定靶');
 assert.equal(await page.locator('.weapon-card[aria-disabled="false"]').count(),7);
 await page.locator('#pause-button').click();
 await page.locator('[data-action="resume"]').waitFor({state:'visible'});
 await page.locator('[data-action="resume"]').click();
 assert.equal(await page.locator('#enemy-name').textContent(),'固定靶');
 await page.keyboard.press('Escape');
 await page.locator('[data-action="restart"]').click();
 await page.waitForFunction(()=>!document.querySelector('#fire-button').disabled);
 assert.equal(await page.locator('#enemy-name').textContent(),'固定靶','restarting preserves practice mode');
 assert.equal(await page.locator('.weapon-card[aria-disabled="false"]').count(),7);
 await page.locator('[data-weapon="meteor"]').click();
 const ammo=await page.locator('[data-ammo="meteor"]').textContent();
 await page.locator('#fire-button').click();
 await page.waitForFunction(()=>!document.querySelector('#fire-button').disabled,null,{timeout:45000});
 assert.equal(await page.locator('[data-ammo="meteor"]').textContent(),ammo);
 assert.equal(await page.locator('#enemy-hp-text').textContent(),'100');
 assert.equal(await page.locator('#enemy-name').textContent(),'固定靶');
 assert.deepEqual(errors,[]);
 await mkdir('_qa/steel-practice',{recursive:true});
 await page.screenshot({path:'_qa/steel-practice/practice-after-shot.png'});
 console.log('PASS: practice entry, seven weapons, pause/resume, practice restart, target reset and unlimited ammunition.');
}finally{await browser?.close();await app.close();await rm(dataDir,{recursive:true,force:true});}
